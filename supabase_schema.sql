-- Move any older admin account out of the student account table.
insert into public.admin_signup (full_name, phone, email, username, password, role)
select full_name, phone, email, username, password, 'admin'
from public.student_signup
where role = 'admin'
on conflict (username) do nothing;

delete from public.student_signup where role = 'admin';

